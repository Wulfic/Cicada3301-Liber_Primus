best_overall_score = -float('inf')
best_overall_key = None

t0 = time.time()
NUM_RESTARTS = 500

for restart in range(NUM_RESTARTS):
    # Initialize: use HC key with random perturbation of unknown positions
    key = list(hc_key)
    if restart > 0:
        for b in unknown:
            key[b] = random.randint(0, MOD-1)
    
    dec = decrypt(key)
    score = qg_score(dec)
    
    best_key_sa = list(key)
    best_score_sa = score
    
    # First do hill climbing to get to a local optimum
    improved = True
    while improved:
        improved = False
        random.shuffle(unknown)
        for b in unknown:
            best_val = key[b]
            best_s = score
            for v in range(MOD):
                if v == key[b]: continue
                key[b] = v
                dec = decrypt(key)
                s = qg_score(dec)
                if s > best_s:
                    best_s = s
                    best_val = v
            key[b] = best_val
            if best_s > score:
                score = best_s
                improved = True
            dec = decrypt(key)
    
    if score > best_score_sa:
        best_score_sa = score
        best_key_sa = list(key)
    
    # Then SA phase: perturbations around the local optimum
    T0 = 5.0
    T_end = 0.01
    n_steps = 50000
    
    for step in range(n_steps):
        T = T0 * (T_end/T0) ** (step / n_steps)
        
        # Pick random unknown position and random new value
        b = random.choice(unknown)
        old_val = key[b]
        new_val = random.randint(0, MOD-2)
        if new_val >= old_val:
            new_val += 1
        
        key[b] = new_val
        dec = decrypt(key)
        new_score = qg_score(dec)
        
        delta = new_score - score
        if delta > 0 or random.random() < math.exp(delta / T):
            score = new_score
            if score > best_score_sa:
                best_score_sa = score
                best_key_sa = list(key)
        else:
            key[b] = old_val
            dec = decrypt(key)
    
    if best_score_sa > best_overall_score:
        best_overall_score = best_score_sa
        best_overall_key = list(best_key_sa)
        txt = show_text_with_words(best_key_sa)
        elapsed = time.time() - t0
        print(f"\n[{restart+1:4d}] score={best_score_sa:.2f} ({elapsed:.0f}s)", flush=True)
        print(f"  {txt[:150]}", flush=True)
    
    if (restart+1) % 100 == 0:
        elapsed = time.time() - t0
        print(f"--- {restart+1}/{NUM_RESTARTS} ({elapsed:.0f}s) best={best_overall_score:.2f} ---", flush=True)

