def decrypt(key):
    return [(cipher[i] - key[i%KLEN]) % MOD for i in range(N)]

def qg_score(dec):
    s = 0.0
    for i in range(len(dec)-3):
        s += qg_logp.get((dec[i], dec[i+1], dec[i+2], dec[i+3]), FLOOR)
    return s

def show_text_with_words(key):
    dec = decrypt(key)
    result = []
    rune_idx = 0
